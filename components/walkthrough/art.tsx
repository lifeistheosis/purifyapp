"use client";

// The walkthrough's line drawings: monochrome, architectural and
// geographic, as the owner's specification asks ("monochrome architectural /
// geographic line illustrations with gyroscope parallax"). Each is three
// layers of plain path data, far, middle and near, so the card can slide
// them at three depths as the phone tilts (./useTilt.ts sets --tx and --ty on
// the frame). Every stroke carries pathLength 1 and draws itself in when the
// card opens, far layer first; reduced motion shows them drawn and still
// (app/globals.css, "Walkthroughs").
//
// Drawn on a 320 by 200 field, in currentColor, so a card sets the ink.

import type { ArtId } from "@/lib/walkthroughs/types";

type Dot = [x: number, y: number, r: number];
type Layer = { paths: string[]; dots?: Dot[] };
type Drawing = { far: Layer; mid: Layer; near: Layer };

/** A circle as a path, so it can draw itself like every other stroke. */
function ring(cx: number, cy: number, r: number): string {
  return `M${cx - r} ${cy} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0`;
}

const WAVES = (y: number, amp = 6) =>
  `M0 ${y} ` +
  Array.from({ length: 8 }, (_, i) => {
    const x = i * 40;
    return `C${x + 10} ${y - amp} ${x + 30} ${y + amp} ${x + 40} ${y}`;
  }).join(" ");

