export const ART_IDS = Object.keys(ART) as ArtId[];

const LAYERS = ["far", "mid", "near"] as const;

/**
 * One drawing. `drawn` replays the stroke-in each time it turns true; the
 * parent frame owns the tilt (./useTilt.ts) through CSS variables.
 */
export function WalkArt({ id, drawn = true, className }: { id: ArtId; drawn?: boolean; className?: string }) {
  const art = ART[id];
  return (
    <svg
      viewBox="0 0 320 200"
      className={className}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.3}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      data-drawn={drawn ? "true" : "false"}
    >
      {LAYERS.map((layer) => (
        <g key={layer} className={`walk-art-${layer}`}>
          {art[layer].paths.map((d, i) => (
            <path key={i} d={d} pathLength={1} className="walk-stroke" />
          ))}
          {art[layer].dots?.map(([x, y, r], i) => (
            <circle key={`d${i}`} cx={x} cy={y} r={r} fill="currentColor" stroke="none" className="walk-dot" />
          ))}
        </g>
      ))}
    </svg>
  );
}
